type SimpleIcon = {
  title: string;
  path: string;
};

function decodeEntities(value: string) {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'");
}

async function fetchIcon(slug: string, version: string): Promise<SimpleIcon> {
  const response = await fetch(
    `https://unpkg.com/simple-icons@${version}/icons/${slug}.svg`,
    {
      headers: {
        Accept: "image/svg+xml",
        "User-Agent": "family-tree-icon-generator/1.0",
      },
    },
  );
  if (!response.ok) {
    throw new Error(`Simple Icons returned ${response.status} for "${slug}".`);
  }
  const svg = await response.text();
  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\bd="([^"]+)"/g)].map(match => match[1]);
  if (!title || !paths.length) {
    throw new Error(`Could not read the SVG for "${slug}".`);
  }
  return {
    title: decodeEntities(title),
    path: paths.join(" "),
  };
}

const metadata = await fetch("https://registry.npmjs.org/simple-icons/latest", {
  headers: { "User-Agent": "family-tree-icon-generator/1.0" },
});
if (!metadata.ok) {
  throw new Error(`Could not read the Simple Icons version (${metadata.status}).`);
}
const version = ((await metadata.json()) as { version: string }).version;

const icons: Record<string, SimpleIcon> = {};
for (const slug of SLUGS) {
  icons[slug] = await fetchIcon(slug, version);
}

const output = `// Generated by scripts/generate-simple-icons.ts. Do not edit by hand.
// Source: https://simpleicons.org, simple-icons v${version} (CC0 1.0 Universal).
// Run \`pnpm icons:generate\` after changing the curated slug list.

export type SimpleIcon = {
  title: string;
  path: string;
};

export const SIMPLE_ICONS: Record<string, SimpleIcon> = ${JSON.stringify(icons, null, 2)};
`;

const directory = path.dirname(fileURLToPath(import.meta.url));
await writeFile(
  path.join(directory, "..", "src", "lib", "simple-icons.generated.ts"),
  output,
  "utf8",
);
console.log(`Wrote ${SLUGS.length} Simple Icons to src/lib/simple-icons.generated.ts.`);
